import pandas as pd

# 1. Load the CSV dataset into a DataFrame called 'df'
df = pd.read_csv('loan_dataset_20000.csv')

# 2. Check the size: (number of rows, number of columns)
print("Dataset Dimensions (Rows, Columns):", df.shape)

# 3. Check for any missing (NaN / null) values across all columns
missing_values = df.isnull().sum()
print("\nMissing values per column:\n", missing_values[missing_values > 0])

# 4. View the top 5 rows
df.head()

# 1. Count how many borrowers paid back (1) vs defaulted (0)
target_counts = df['loan_paid_back'].value_counts()
print("Raw Counts:")
print(target_counts)

# 2. Convert raw counts into percentages
target_proportions = df['loan_paid_back'].value_counts(normalize=True) * 100
print("\nPercentage Distribution (%):")
print(target_proportions.round(2))

# Group by loan_paid_back (0 = Default, 1 = Paid Back) and compare key financial metrics
cohort_comparison = df.groupby('loan_paid_back')[[
    'credit_score',
    'debt_to_income_ratio',
    'interest_rate',
    'loan_amount',
    'annual_income'
]].agg(['mean', 'median']).round(2)

# Display the cohort comparison table
print("=== Cohort Comparison: Defaulted (0) vs Paid Back (1) ===")
cohort_comparison.T

# 1. Calculate the Pearson correlation between annual_income and monthly_income
income_corr = df[['annual_income', 'monthly_income']].corr().iloc[0, 1]
print(f"Correlation between Annual and Monthly Income: {income_corr:.6f}")

# 2. Check maximum difference from exact formula: monthly = annual / 12
max_diff = (df['annual_income'] / 12 - df['monthly_income']).abs().max()
print(f"Maximum difference from (annual_income / 12): ${max_diff:.4f}")

# 3. Drop 'monthly_income' from our working dataset
df_clean = df.drop(columns=['monthly_income'])
print(f"Remaining columns count in df_clean: {df_clean.shape[1]}")

# 1. Separate Predictor Matrix (X) and Target Vector (y)
X = df_clean.drop(columns=['loan_paid_back'])
y = df_clean['loan_paid_back']

# 2. Automatically detect numerical and categorical columns
numerical_cols = X.select_dtypes(include=['int64', 'float64']).columns.tolist()
categorical_cols = X.select_dtypes(include=['object']).columns.tolist()

# 3. Print the lists to inspect feature classification
print(f"Total Predictor Features: {X.shape[1]}")
print(f"\nNumerical Columns ({len(numerical_cols)}):")
print(numerical_cols)
print(f"\nCategorical Columns ({len(categorical_cols)}):")
print(categorical_cols)

from sklearn.model_selection import train_test_split

# Perform stratified 80/20 train-test split
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

# Print partition sizes
print(f"Training features shape: {X_train.shape} | Training targets: {y_train.shape}")
print(f"Testing features shape:  {X_test.shape}  | Testing targets:  {y_test.shape}")

# Verify exact default percentages in both splits
train_default_pct = (y_train == 0).mean() * 100
test_default_pct = (y_test == 0).mean() * 100

print(f"\nTraining Set Default Rate: {train_default_pct:.2f}%")
print(f"Testing Set Default Rate:  {test_default_pct:.2f}%")

from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.compose import ColumnTransformer

# Build the preprocessor object
preprocessor = ColumnTransformer(
    transformers=[
        ('num', StandardScaler(), numerical_cols),
        ('cat', OneHotEncoder(drop='first', handle_unknown='ignore'), categorical_cols)
    ]
)

# Fit and transform the training data to inspect the transformed feature space
X_train_processed = preprocessor.fit_transform(X_train)
X_test_processed = preprocessor.transform(X_test)

print("Original numerical features:", len(numerical_cols))
print("Original categorical features:", len(categorical_cols))
print(f"Transformed training matrix shape: {X_train_processed.shape}")
print(f"Transformed testing matrix shape:  {X_test_processed.shape}")

from sklearn.pipeline import Pipeline
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report, roc_auc_score, confusion_matrix

# 1. Assemble the end-to-end Pipeline
lr_pipeline = Pipeline([
    ('preprocessor', preprocessor),
    ('classifier', LogisticRegression(max_iter=1000, class_weight='balanced', random_state=42))
])

# 2. Fit the pipeline on raw training data
lr_pipeline.fit(X_train, y_train)

# 3. Predict on unseen test data
y_pred_lr = lr_pipeline.predict(X_test)
y_prob_lr = lr_pipeline.predict_proba(X_test)[:, 1]

# 4. Print core evaluation metrics
print("=== Logistic Regression Performance on Test Set (4,000 Borrowers) ===")
print(classification_report(y_test, y_pred_lr, target_names=['Default (0)', 'Paid Back (1)']))
print(f"ROC-AUC Score: {roc_auc_score(y_test, y_prob_lr):.4f}")

from sklearn.ensemble import RandomForestClassifier

# 1. Assemble the Random Forest Pipeline
rf_pipeline = Pipeline([
    ('preprocessor', preprocessor),
    ('classifier', RandomForestClassifier(
        n_estimators=100,
        class_weight='balanced',
        random_state=42,
        n_jobs=-1
    ))
])

# 2. Fit on training data
rf_pipeline.fit(X_train, y_train)

# 3. Predict on unseen test data
y_pred_rf = rf_pipeline.predict(X_test)
y_prob_rf = rf_pipeline.predict_proba(X_test)[:, 1]

# 4. Print core evaluation metrics
print("=== Random Forest Performance on Test Set (4,000 Borrowers) ===")
print(classification_report(y_test, y_pred_rf, target_names=['Default (0)', 'Paid Back (1)']))
print(f"ROC-AUC Score: {roc_auc_score(y_test, y_prob_rf):.4f}")

from sklearn.metrics import confusion_matrix
import pandas as pd

# Cost assumptions
COST_MISSED_DEFAULT = 15000  # Approving someone who defaults
COST_FALSE_ALARM = 50        # Flagging a good borrower for manual check

# Extract confusion matrices
# In our target encoding: 0 = Default, 1 = Paid Back
cm_lr = confusion_matrix(y_test, y_pred_lr)
cm_rf = confusion_matrix(y_test, y_pred_rf)

# Logistic Regression breakdown
# Row 0: Actual Defaults -> cm[0,0] = Caught Defaults, cm[0,1] = Missed Defaults
# Row 1: Actual Paid Back -> cm[1,0] = False Alarms, cm[1,1] = Correct Repayments
lr_missed = cm_lr[0, 1]
lr_false_alarms = cm_lr[1, 0]
lr_total_cost = (lr_missed * COST_MISSED_DEFAULT) + (lr_false_alarms * COST_FALSE_ALARM)

# Random Forest breakdown
rf_missed = cm_rf[0, 1]
rf_false_alarms = cm_rf[1, 0]
rf_total_cost = (rf_missed * COST_MISSED_DEFAULT) + (rf_false_alarms * COST_FALSE_ALARM)

# Financial audit table
loss_audit = pd.DataFrame({
    'Model': ['Logistic Regression (Balanced)', 'Random Forest (Balanced)'],
    'Accuracy': ['81%', '90%'],
    'Default Recall': ['73%', '52%'],
    'Missed Defaults (Uncaught)': [lr_missed, rf_missed],
    'False Alarms (Manual Review)': [lr_false_alarms, rf_false_alarms],
    'Financial Loss ($)': [f"${lr_total_cost:,.2f}", f"${rf_total_cost:,.2f}"],
    'Capital Preserved': [f"+${(rf_total_cost - lr_total_cost):,.2f}", "Baseline"]
})

print("=== Balance Sheet Impact Simulation (Holdout 4,000 Loans) ===")
loss_audit